#!/bin/sh
# service.sh - M2 offline servicing on the F2 copy using wimlib (file-level).
#
# Removes the 2017 inbox PCIe package and stages the 2015 OEM package plus the
# board nvram. This is a wimlib file-level approximation of DISM offline
# servicing: it changes the DriverStore file layout, NOT the Windows driver
# database (DRIVERS hive) or PnP state. True DISM /Add-Driver /Remove-Driver
# requires Windows. Label every result synthetic F2. See docs/05.
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
WORK="$ROOT/qemu/work"
OEM="$ROOT/drivers/mipad2-oficial/wifi"
NVRAM="$ROOT/drivers/nvram-delta/4356r2nvram.txt"
FR='/Windows/System32/DriverStore/FileRepository'
TGT='bcmwdidhdpcie.inf_amd64_977dcc915465b0e9'

[ -f "$WORK/f2.wim" ] || { echo "service: run build-media.sh first (no f2.wim)" >&2; exit 1; }
cp "$WORK/f2.wim" "$WORK/serviced.wim"

# Representative DriverStore folder for the staged OEM package. The real suffix
# is generated by Windows PnP/DISM; here it is derived from the OEM INF hash and
# is a synthetic stand-in (documented, not a real PnP hash).
OEMHASH=$(sha256sum "$OEM/oem25.inf" | cut -c1-16)
OEMDEST="$FR/oem25.inf_amd64_$OEMHASH"

echo "== remove the 2017 inbox package: $TGT"
wimlib-imagex update "$WORK/serviced.wim" 1 --command="delete --recursive $FR/$TGT"

echo "== stage the 2015 OEM package -> $OEMDEST"
wimlib-imagex update "$WORK/serviced.wim" 1 --command="add $OEM $OEMDEST"

echo "== nvram fallback copy into System32\\drivers (PnP CopyFiles not run offline)"
wimlib-imagex update "$WORK/serviced.wim" 1 \
  --command="add $NVRAM /Windows/System32/drivers/4356r2nvram.txt"

echo "== verify: 2017 package absent"
if wimlib-imagex dir "$WORK/serviced.wim" 1 --path="$FR/$TGT" >/dev/null 2>&1; then
  echo "ERROR: 2017 package still present"; exit 1
else
  echo "OK: $TGT removed"
fi
echo "== verify: staged OEM package contents"
wimlib-imagex dir "$WORK/serviced.wim" 1 --path="$OEMDEST"
echo "== verify: nvram in System32\\drivers"
wimlib-imagex dir "$WORK/serviced.wim" 1 --path='/Windows/System32/drivers/4356r2nvram.txt'
echo "== serviced image hash"
sha256sum "$WORK/serviced.wim"
echo "== done: $WORK/serviced.wim (F2 serviced, synthetic)"
